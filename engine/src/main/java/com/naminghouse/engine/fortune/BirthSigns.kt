package com.naminghouse.engine.fortune

/** 12간지 띠 */
data class Ttii(
    val name: String,
    /** 지지 한자 (子·丑…) */
    val branch: String,
    /** 지지 한글 음 */
    val branchKo: String,
    val traits: String,
)

/** 서양 12별자리 */
data class StarSign(
    val name: String,
    /** 화면에 쓰는 기간 표기 */
    val period: String,
    val traits: String,
)

/**
 * 띠와 별자리 — 이름 자체와는 무관한 '태어난 때'의 부가 정보.
 * 작명왕도 이름 풀이에 같이 실어 주므로 맞춰 넣는다.
 */
object BirthSigns {

    /**
     * 사주 년지(年支)로 띠를 정한다.
     *
     * 양력 1월 1일이 아니라 **입춘**이 해의 경계라 년지를 그대로 쓰는 것이 맞다.
     * (예: 2026-01-20 생은 달력상 2026년이지만 입춘 전이라 아직 을사년 뱀띠)
     */
    fun ttiiOf(yearBranch: String): Ttii? = TTII[yearBranch]

    /** 양력 생일로 별자리를 정한다(음력 입력이면 양력으로 바꾼 날짜를 넣을 것). */
    fun starSignOf(month: Int, day: Int): StarSign? =
        RANGES.firstOrNull { r ->
            // 염소자리처럼 해를 넘기는 구간이 있어 시작월·끝월을 각각 본다
            (month == r.m1 && day >= r.d1) || (month == r.m2 && day <= r.d2)
        }?.sign

