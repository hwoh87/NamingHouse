/**
 * 십신 × 기둥 키워드 카드 — 40개(십신 10 × 기둥 4).
 *
 * 사용자가 사주표의 십신 셀을 탭하면 [SipsinPillarCard] 한 장이 다이얼로그로 노출.
 * 다른 만세력 사이트의 위치별 상세 해석을 압축해 친근·정확 톤으로 작성.
 *
 * 위치 의미 베이스라인:
 *   - 년주(idx 3) = 조상·뿌리·초년 (~20세)
 *   - 월주(idx 2) = 부모·사회·청년 (20~40)
 *   - 일주(idx 1) = 본인·배우자·중년 (40~60)
 *   - 시주(idx 0) = 자식·말년 (60+)
 *
 * 십신 베이스:
 *   比肩 형제·자존심   |  劫財 경쟁자·이복   |  食神 표현·복록    |  傷官 재능·반항
 *   偏財 활동재·아버지 |  正財 안정재·정실   |  偏官 압박·권력    |  正官 명예·규범
 *   偏印 직관·특수    |  正印 학문·어머니
 *
 * 후속(Phase 4): 같은 데이터를 LLM 컨텍스트로 주입해 통합 풀이 결제 트리거.
 */

/**
 * 동반 조건별 변주 한 줄. condition 칩 + effect 본문.
 *
 * @param requires effect가 뚜렷이 발현되기 위한 추가 전제(예: 식신제살은 신강 전제).
 *   비어 있으면 무조건 발현. matchesVariation(condition)으로 1차 매칭된 뒤,
 *   이 전제가 충족되지 않으면 UI에서 "~일 때 더 뚜렷" 단서로 안내.
 *
 * tone(흉/길/중립)·domains(관계/재물/직업/건강/학업)는 effect 키워드에서 파생 —
 * 177개 변주에 일일이 주석을 달지 않고 일관 규칙으로 산출(향후 추가 변주에도 자동 적용).
 */
data class SipsinVariation(
    val condition: String,             // "식상 동반"
    val effect: String,                // "재능을 사업으로 → 크게 성공"
    val requires: List<String> = emptyList(),  // 발현 전제: "신강"/"신약"/"용신" 등
    val toneOverride: String? = null   // 파생 tone이 부정확할 때만 명시("길"/"흉"/"중립")
) {
    /** 흉/길/중립 — SipsinPattern.tone과 동일 컨벤션. UI 색상·AI 가중용. */
    val tone: String get() = toneOverride ?: deriveVariationTone(effect)

    /** 영향 도메인(복수 가능). AI 그룹핑·필터용. */
    val domains: List<String> get() = deriveVariationDomains(condition, effect)
}

// 흉 신호: 정통 흉 패턴 용어 + 강한 손실/갈등 어휘. (caveat 어휘 "주의/필요/고독"은 의도적으로 제외)
private val VAR_TONE_HYUNG = listOf(
    "견관", "탈식", "쟁재", "재생살", "모자멸자", "속성속패",
    "손실", "손재", "분쟁", "불화", "갈등", "약화", "막힘", "위험", "짓눌", "흔들"
)
private val VAR_TONE_GIL = listOf(
    "생재", "상생", "귀인", "대성", "대귀대부", "부귀", "부자", "부유", "명성",
    "출세", "성공", "풍요", "두각", "빛남", "축적", "자산", "발달", "안정", "인덕"
)

/** effect 본문에서 흉/길/중립 파생. 흉 패턴 우선. */
internal fun deriveVariationTone(effect: String): String = when {
    VAR_TONE_HYUNG.any { effect.contains(it) } -> "흉"
    VAR_TONE_GIL.any { effect.contains(it) } -> "길"
    else -> "중립"
}

private val VAR_DOMAIN_RULES: List<Pair<String, List<String>>> = listOf(
    "관계" to listOf("부부", "배우자", "이성", "결혼", "가정", "인척"),
    "재물" to listOf("재물", "재산", "부자", "부유", "사업", "자산", "금전", "축적", "재정"),
    "직업" to listOf("출세", "관직", "직장", "명성", "리더", "전문직", "전문 기술", "관운"),
    "건강" to listOf("건강", "신체", "질병", "신변"),
    "학업" to listOf("학문", "학업", "시험", "연구", "교육", "공부")
)

/** condition+effect 키워드에서 도메인(복수) 파생. */
internal fun deriveVariationDomains(condition: String, effect: String): List<String> {
    val hay = "$condition $effect"
    return VAR_DOMAIN_RULES.filter { (_, kws) -> kws.any { hay.contains(it) } }.map { it.first }
}

/**
 * 일반론 "특성" bullet 한 줄.
 *
 * @param text 표시 본문 (앞에 "• " 자동 prefix, 매칭 시 "★ " prefix)
 * @param condition matchesVariation 평가용 조건 키. null = 무조건 적용(일반 트레이트).
 *
 * 사용처: SipsinGlobal.essentialTraits — UI는 사용자 SipsinContext 와 매칭해
 * 매칭 bullet 만 노란 강조, 비매칭 조건 bullet 은 dim 회색, 무조건 bullet 은 기본 톤.
 */
data class SipsinTrait(
    val text: String,
    val condition: String? = null
)

/**
 * 십신별 1개의 글로벌 메타 (위치 무관 공통 정보).
 *
 * 자료(다른 만세력 사이트의 십신 표)의 상징/특성/강약/다수 패턴은
 * 위치(년·월·일·시)와 무관하게 같은 십신이면 동일하므로 카드별 4번 반복 X.
 *
 * 시트 상단에 노출되어 위치별 카드(SipsinPillarCard) 위에 풀어 보임.
 */
data class SipsinGlobal(
    val sipsinHanja: String,
    val sipsinKr: String,
    val tagline: String = "",      // 한 줄 본질 (예: "동지·자기 주관·주도성의 엔진")
    val symbolMale: String,        // "남자에게는 ..."
    val symbolFemale: String,      // "여자에게는 ..."
    val essentialNature: String,   // 자료의 "특성" 요약 (긴 단락 가능 — fallback)
    val essentialTraits: List<SipsinTrait> = emptyList(),  // bullet 단위 매칭 (있으면 우선)
    val whenStrong: String,        // 강할 때 본문
    val whenWeak: String,          // 약할 때 본문
    val multiPattern: String,      // 3개 이상 / 4개 이상 패턴
    val careerHint: String = ""    // 직업 친화 한 줄 (예: "공무원·법조·교사·기업 관리자")
)

/** 십신×기둥 조합 한 카드. */
data class SipsinPillarCard(
    val sipsinHanja: String,
    val sipsinKr: String,
    val pillarIndex: Int,        // 0=시 1=일 2=월 3=년
    val pillarLabel: String,     // "년주" 등
    val areaMeta: String,        // "조상·초년" 등
    val coreMeaning: String,
    val strengths: List<String>,
    val cautions: List<String>,
    val variations: List<SipsinVariation>
)

/* ─ 위치 메타 ─ */
private const val P_HOUR = 0
private const val P_DAY = 1
private const val P_MONTH = 2
private const val P_YEAR = 3
private val PILLAR_LABEL = mapOf(
    P_HOUR to ("시주" to "자식·말년"),
    P_DAY to ("일주" to "본인·배우자"),
    P_MONTH to ("월주" to "부모·사회"),
    P_YEAR to ("년주" to "조상·초년")
)

private fun card(
    hanja: String, kr: String, pillar: Int,
    core: String, str: List<String>, cau: List<String>,
    vars: List<SipsinVariation>
): Pair<Pair<String, Int>, SipsinPillarCard> {
    val (label, area) = PILLAR_LABEL[pillar]!!
    return (hanja to pillar) to SipsinPillarCard(
        hanja, kr, pillar, label, area, core, str, cau, vars
    )
}

