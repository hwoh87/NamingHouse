# 같은 요즘 이름도 없다). 그래서 통계가 아니라 **세대 표지 음절**로 골랐다:
#   자·순·숙·옥·철·환·식·섭·표·병·광·덕·봉·만·두·택·학·홍·갑·계·방·삼·귀 …
# 와, 음절만으로는 안 잡히지만 명백히 부모 세대인 이름(미영·현주·수정·은정 …).
#
# 판단이 섞인 목록이라 의도적으로 보수적으로 잡았다 — 요즘 아이에게 붙여도
# 어색하지 않은 이름은 남겼다(재현·성준·시현·혜원·다혜·아름·보람 …).
# tier 3 으로 내려도 목록에서 사라지지는 않는다. 외자 모드와 tier 상한을 3 으로
# 연 호출부에서는 그대로 후보가 된다.
# ─────────────────────────────────────────────────────────────
DEMOTE_TO_TIER3 = """
경수 경아 경윤 경택 경한 경호 경희 관우 관호 광민 광수 광진 규나 규진
기범 기석 기태 기훈 남우 남진 남훈 노민 대건 대영 대운 대웅 덕현
두현 두호 두환 만호 명아 명우 명주 명진 명현 문경 문수 문호
미나 미단 미리 미영 미주 민정 백설 백승 백아 백호 범석 범수
병기 병윤 병현 병훈 보경 보성 봉준 봉현 상범 석민 석원 석호
선영 성엽 성욱 순영 승기 승엽 승택 승표 시열 신영 신욱
애나 애리 여호 연규 연택 연호 영광 영주 영표 영훈 용재 우신 원호
유미 유정 윤정 인성 자영 정운 종민 종우 준상 지숙 지영 진주
창민 철민 학수 향기 향아 현탁 형민 호성 호정 홍민 홍석 훈석 훈재 희나
수정 현주 혜진 은정 지혜 소영 나영 진아 유리 지선 은주 유경 세림 정연
"""


def parse(block: str) -> list:
    return [w for w in block.split() if w]


def valid(name: str) -> bool:
    if not 1 <= len(name) <= 3:
        return False
    return all(0xAC00 <= ord(ch) <= 0xD7A3 for ch in name)


STATS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..",
    "engine", "src", "main", "assets", "name-stats.tsv",
)


def load_stats():
    """대법원 실측 통계 — {이름: (성별, 최근최고순위, 총건수)}. 없으면 빈 dict."""
    if not os.path.exists(STATS):
        print("  (name-stats.tsv 없음 — 큐레이션 목록만 사용)", file=sys.stderr)
        return {}
    out = {}
    with open(STATS, encoding="utf-8") as f:
        next(f, None)
        for line in f:
            c = line.rstrip("\n").split("\t")
            if len(c) < 5:
                continue
            name, m, fem = c[0], int(c[2] or 0), int(c[3] or 0)
            ranks = [int(p.split(":")[1]) for p in c[4].split(",") if ":" in p]
            total = m + fem
            if total == 0:
                continue
            pct = round(m * 100 / total)
            gender = "M" if pct >= 70 else "F" if pct <= 30 else "U"
            out[name] = (gender, min(ranks) if ranks else None, total)
    return out


def tier_from_rank(rank):
    """실측 순위 → tier. 순위가 없으면 None(큐레이션 tier 유지)."""
    if rank is None:
        return None
    if rank <= 100:
        return 1
    if rank <= 300:
        return 2
    return 3


def main() -> int:
    sources = [
        ("M", 1, parse(M1)), ("F", 1, parse(F1)),
        ("M", 2, parse(M2) + parse(M2B)), ("F", 2, parse(F2) + parse(F2B)),
        ("M", 3, parse(M3) + parse(M3B)), ("F", 3, parse(F3) + parse(F3B)),
        ("M", 3, parse(M_SINGLE)), ("F", 3, parse(F_SINGLE)),
    ]

    # name -> {"genders": set, "tier": int}
    table = {}
    for gender, tier, names in sources:
        for name in names:
            if not valid(name):
                print(f"  건너뜀(형식 오류): {name!r}", file=sys.stderr)
                continue
            name = unicodedata.normalize("NFC", name)
            slot = table.setdefault(name, {"genders": set(), "tier": tier})
            slot["genders"].add(gender)
            slot["tier"] = min(slot["tier"], tier)

    for name in parse(U_EXTRA) + parse(U_SINGLE):
        name = unicodedata.normalize("NFC", name)
        if not valid(name):
            continue
        slot = table.setdefault(name, {"genders": set(), "tier": 2})
        slot["genders"] |= {"M", "F"}

    # 대법원 실측 통계를 얹는다. 손으로 매긴 tier·성별보다 실제 출생신고 집계가 정확하다.
    stats = load_stats()
    added = 0
    for name, (gender, rank, _total) in stats.items():
        if not valid(name):
            continue
        slot = table.get(name)
        if slot is None:
            # 통계에는 있는데 큐레이션 목록에서 빠진 이름(가은·민우·서은 등)
            table[name] = {"genders": {gender} if gender != "U" else {"M", "F"},
                           "tier": tier_from_rank(rank) or 2, "fromStats": True}
            added += 1
        else:
            slot["genders"] = {gender} if gender != "U" else {"M", "F"}
            t = tier_from_rank(rank)
            if t is not None:
                slot["tier"] = t
    print(f"  실측 통계 반영: {len(stats)}개 (신규 {added}개)")

    # 세대 강등 — 실측 통계보다 뒤에 둔다. 통계에 최근 순위가 잡힌 이름은 실제로
    # 지금 쓰이고 있다는 증거이므로 강등 목록에 있더라도 되돌린다(손으로 매긴
    # 판단보다 집계가 우선이라는 이 파일의 기존 원칙과 같다).
    demoted = 0
    for name in parse(DEMOTE_TO_TIER3):
        name = unicodedata.normalize("NFC", name)
        slot = table.get(name)
        if slot is None:
            print(f"  (강등 목록에 없는 이름: {name})", file=sys.stderr)
            continue
        if stats.get(name, (None, None, None))[1] is not None:
            continue  # 최근 출생신고 순위권 — 강등하지 않는다
        if slot["tier"] < 3:
            slot["tier"] = 3
            demoted += 1
    print(f"  세대 강등: {demoted}개 → tier 3")

    rows = []
    for name, slot in table.items():
        gender = "U" if slot["genders"] == {"M", "F"} else next(iter(slot["genders"]))
        rows.append((name, gender, slot["tier"]))
    rows.sort(key=lambda r: (r[2], r[0]))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("name\tgender\ttier\n")
        for name, gender, tier in rows:
            f.write(f"{name}\t{gender}\t{tier}\n")

    total = len(rows)
    m = sum(1 for _, g, _ in rows if g in ("M", "U"))
    fem = sum(1 for _, g, _ in rows if g in ("F", "U"))
    t1 = sum(1 for _, _, t in rows if t == 1)
    print(f"{os.path.relpath(OUT)}  총 {total}개")
    print(f"  남아용 {m} · 여아용 {fem} · 중성 {sum(1 for _, g, _ in rows if g == 'U')}")
    print(f"  tier1 {t1} · tier2 {sum(1 for _, _, t in rows if t == 2)} · tier3 {sum(1 for _, _, t in rows if t == 3)}")

    assert total >= 900, f"이름 수 부족: {total}"
    assert m >= 350 and fem >= 350, f"성별 균형 부족: M={m} F={fem}"
    assert t1 >= 150, f"tier1 부족: {t1}"
    print("검증 통과")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
